#!/usr/bin/env bash
# Regenerates crates/argowei-core/registry/oui.tsv from the IEEE MA-L registry.
#
# Usage: bash scripts/update-oui.sh [path/to/oui.txt]
#
# Without an argument the registry is downloaded from IEEE. IEEE's web
# application firewall sometimes rejects non-browser clients; in that case
# download https://standards-oui.ieee.org/oui/oui.txt in a browser and pass
# the file path. Any file in IEEE's oui.txt format works (for example
# /usr/share/hwdata/oui.txt from the hwdata package).
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
out="$root/crates/argowei-core/registry/oui.tsv"
url="https://standards-oui.ieee.org/oui/oui.txt"

if [[ $# -ge 1 ]]; then
    src="$1"
    origin="$(basename "$src")"
else
    src="$(mktemp)"
    trap 'rm -f "$src"' EXIT
    curl --fail --silent --show-error "$url" -o "$src"
    origin="$url"
fi

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

# Keep "XXXXXX<TAB>Organization" from the "(base 16)" lines. Entries the
# registrant hides ("Private") carry no information and are dropped.
LC_ALL=C awk -F'\t+' '
    /\(base 16\)/ {
        split($1, id, " ")
        name = $2
        gsub(/^[ \t]+|[ \t\r]+$/, "", name)
        if (name != "" && name != "Private") print toupper(id[1]) "\t" name
    }
' "$src" | LC_ALL=C sort -u > "$tmp"

count="$(wc -l < "$tmp")"
if [[ "$count" -lt 10000 ]]; then
    echo "refusing to write: only $count entries parsed from $src" >&2
    exit 1
fi

{
    echo "# IEEE MA-L (OUI) assignments: 24-bit prefix, tab, organization."
    echo "# Generated by scripts/update-oui.sh from: $origin"
    echo "# Generated on: $(date -u +%Y-%m-%d)"
    echo "# See crates/argowei-core/registry/README.md for source and license notes."
    cat "$tmp"
} > "$out"

echo "wrote $count entries to $out"
